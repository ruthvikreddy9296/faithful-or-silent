# Short key segment used in \rv names (dots/dashes fine inside \csname).
KEY = {c: c.replace("p1_", "") for c in CONFIG_ORDER}
SCREEN_THRESHOLD = 0.5  # NLI max-entailment cutoff certifying a trap (phase2_screen.py)


# ---------------------------------------------------------------- formatting
def pct(x, dec=1):
    return f"{100 * x:.{dec}f}\\%"


def pct_bare(x, dec=1):
    return f"{100 * x:.{dec}f}"


def num(x, dec=3):
    return f"{x:.{dec}f}"


def pfmt(p):
    """IEEE-style p-value: scientific for tiny, 3 decimals otherwise."""
    if p >= 0.995:
        return "\\ensuremath{>0.99}"
    if p >= 0.001:
        return f"\\ensuremath{{{p:.3f}}}"
    m, e = f"{p:.2e}".split("e")
    return f"\\ensuremath{{{m}\\times10^{{{int(e)}}}}}"


def tex_escape(s):
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                 ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")]:
        s = s.replace(a, b)
    return s


# ---------------------------------------------------------------- loaders
def load_frontier():
    out = {}
    for arm, suf in ARMS.items():
        rows = json.loads((RESULTS / f"phase1_frontier{suf}.json").read_text())
        out[arm] = {m["config"]: m for m in rows}
        missing = set(CONFIG_ORDER) - set(out[arm])
        assert not missing, f"{arm}: frontier missing configs {missing}"
    return out


def load_stats():
    return {arm: json.loads((RESULTS / f"phase1_stats{suf}.json").read_text())
            for arm, suf in ARMS.items()}


def load_runs():
    """Per-config config.json + retrieval_report.json (authoritative; summary is stale)."""
    out = {}
    for c in CONFIG_ORDER:
        d = RESULTS / f"phase1_{c}"
        cfg = json.loads((d / "config.json").read_text())
        rep_p = d / "retrieval_report.json"
        rep = json.loads(rep_p.read_text()) if rep_p.exists() else {}
        out[c] = {"cfg": cfg, "rep": rep}
    return out


def load_completions(cfg, suf):
    p = RESULTS / f"phase1_{cfg}" / f"completions{suf}.jsonl"
    return [json.loads(l) for l in p.read_text().splitlines()]


def coverage_accuracy():
    """correct/n_answerable (not conditional on answering) — recomputed from raw
    completions because the frontier JSON only stores the conditional form."""
    out = {}
    for arm, suf in ARMS.items():
        out[arm] = {}
        for c in CONFIG_ORDER:
            rows = load_completions(c, suf)
            ans = [r for r in rows if r["answerable"]]
            correct = sum(1 for r in ans
                          if parse_response(r["response_text"])[0] == "answer"
                          and parse_response(r["response_text"])[1] == r["gold_label"])
            out[arm][c] = correct / len(ans)
    return out


def certified_fa(screen):
    """FA restricted to the NLI-certified trap subset, per arm/config."""
    certified = {o["qid"] for o in screen if o["max_entailment"] <= SCREEN_THRESHOLD}
    out = {}
    for arm, suf in ARMS.items():
        out[arm] = {}
        for c in CONFIG_ORDER:
            rows = [r for r in load_completions(c, suf)
                    if not r["answerable"] and r["qid"] in certified]
            answered = sum(1 for r in rows
                           if parse_response(r["response_text"])[0] == "answer")
            out[arm][c] = answered / len(rows)
    return out, certified


def gate_split():
    info = json.loads((RESULTS / "phase1_p1_simgate" / "gate_info.json").read_text())
    rep = json.loads((RESULTS / "phase1_p1_simgate" / "retrieval_report.json").read_text())
    answerable = {r["qid"]: r["answerable"] for r in rep["records"]}
    gated = info["gated_qids"]
    traps = sum(1 for q in gated if not answerable[q])
    answ = sum(1 for q in gated if answerable[q])
    return info["threshold"], traps, answ, len(gated)


# ---------------------------------------------------------------- numbers.tex
def build_numbers(front, stats, runs, covacc, certfa, certified, gate, screen):
    rv = {}

    def put(key, val):
        assert key not in rv, f"duplicate rv key {key}"
        rv[key] = val

    # design constants
    corpus = json.loads((RESULTS / "corpus_stats.json").read_text())
    put("design.corpus", f"{corpus['phase1']['corpus_passages']:,}".replace(",", "{,}"))
    put("design.chunks", f"{corpus['phase1']['chunks_512tok_16overlap']:,}".replace(",", "{,}"))
    put("design.nansw", "400")
    put("design.nunansw", "250")
    put("design.nquestions", "650")
    put("design.nconfigs", str(len(CONFIG_ORDER)))
    put("design.narms", "3")
    put("design.ncompletions", f"{len(CONFIG_ORDER) * 650 * 3:,}".replace(",", "{,}"))
    put("design.seed", "42")
    put("design.pqau", "15{,}000")
    put("design.refusal", tex_escape(REFUSAL_STRING))

    # per arm/config outcomes
    for arm in ARMS:
        for c in CONFIG_ORDER:
            m, k = front[arm][c], KEY[c]
            put(f"{arm}.{k}.fa", pct(m["false_answer_rate"]))
            put(f"{arm}.{k}.fa.raw", num(m["false_answer_rate"]))
            lo, hi = m["false_answer_rate_ci95"]
            put(f"{arm}.{k}.faci", f"[{pct_bare(lo)}, {pct_bare(hi)}]\\%")
            put(f"{arm}.{k}.frr", pct(m["false_refusal_rate"]))
            put(f"{arm}.{k}.frr.raw", num(m["false_refusal_rate"]))
            put(f"{arm}.{k}.acc", pct(m["accuracy_when_answering"]))
            put(f"{arm}.{k}.acc.raw", num(m["accuracy_when_answering"]))
            put(f"{arm}.{k}.unp", pct(m["unparseable_rate"]))
            put(f"{arm}.{k}.covacc", pct(covacc[arm][c]))
            put(f"{arm}.{k}.certfa", pct(certfa[arm][c]))

    # retrieval
    for c in CONFIG_ORDER:
        rep, cfg, k = runs[c]["rep"], runs[c]["cfg"], KEY[c]
        if rep.get("recall_at_k") is not None:
            put(f"recall.{k}", num(rep["recall_at_k"]))
            put(f"leaks.{k}", str(rep["holdout_leaks"]))
        put(f"k.{k}", str(cfg["top_k"]))

    # paired tests
    for arm in ARMS:
        for e in stats[arm]["mcnemar"]:
            a, b = e["pair"].split(" vs ")
            base = f"{arm}.{KEY[a]}-vs-{KEY[b]}"
            put(f"p.{base}", pfmt(e["mcnemar_p"]))
            if "n01" in e:
                assert e["n01"] + e["n10"] == e["discordant"], e["pair"]
                put(f"nzeroone.{base}", str(e["n01"]))
                put(f"nonezero.{base}", str(e["n10"]))
            put(f"disc.{base}", str(e["discordant"]))
        sp = stats[arm]["spearman_recall_fa"]
        put(f"rho.{arm}", num(sp["rho"], 2))
        put(f"rhop.{arm}", pfmt(sp["p"]))
        put(f"rhon.{arm}", str(sp["n"]))
        sp5 = stats[arm]["spearman_recall_fa_k5"]
        put(f"rho5.{arm}", num(sp5["rho"], 2))
        put(f"rhop5.{arm}", pfmt(sp5["p"]))
        put(f"rhon5.{arm}", str(sp5["n"]))

    # gate
    thr, traps, answ, ngated = gate
    put("gate.thr", num(thr, 3))
    put("gate.trapsblocked", str(traps))
    put("gate.answblocked", str(answ))
    put("gate.ngated", str(ngated))
    for arm in ARMS:
        d_fa = front[arm]["p1_base"]["false_answer_rate"] - front[arm]["p1_simgate"]["false_answer_rate"]
        d_frr = front[arm]["p1_simgate"]["false_refusal_rate"] - front[arm]["p1_base"]["false_refusal_rate"]
        put(f"gate.netfa.{arm}", str(round(d_fa * 250)))
        put(f"gate.netfrr.{arm}", str(round(d_frr * 400)))

    # screen
    put("screen.n", "250")
    put("screen.thr", num(SCREEN_THRESHOLD, 1))
    put("screen.certified", str(len(certified)))
    for t, name in [(0.5, "05"), (0.7, "07"), (0.9, "09")]:
        put(f"screen.above{name}", str(sum(1 for o in screen if o["max_entailment"] > t)))

    # budget-confound bound (results/budget_confound.json, scripts/budget_confound_check.py)
    conf = json.loads((RESULTS / "budget_confound.json").read_text())
    put("confound.verdictthenrefusal",
        str(conf["verdict_then_refusal_anywhere"]["verdict_then_refusal"]))
    for arm in ("qwen", "llama"):
        assert conf["verdict_first_base"][arm]["unparseable"] == 0, arm
        assert conf["verdict_first_base"][arm]["parse_class_not_fixed_in_first_400_chars"] == 0, arm

    # derived ratios (claim 3: scale relocates the trade-off; never hand-type "4x")
    base_ratio = (front["qwen"]["p1_base"]["false_answer_rate"]
                  / front["terra"]["p1_base"]["false_answer_rate"])
    ratios = sorted(front["qwen"][c]["false_answer_rate"] / front["terra"][c]["false_answer_rate"]
                    for c in CONFIG_ORDER
                    if c != "p1_noctx" and front["terra"][c]["false_answer_rate"] > 0)
    median = ratios[len(ratios) // 2] if len(ratios) % 2 else (
        (ratios[len(ratios) // 2 - 1] + ratios[len(ratios) // 2]) / 2)
    put("ratio.fa.qwenterra.base", f"{base_ratio:.2f}")
    put("ratio.fa.qwenterra.median", f"{median:.2f}")

    lines = [HEADER]
    lines += [f"\\defrv{{{k}}}{{{v}}}" for k, v in sorted(rv.items())]
    return "\n".join(lines) + "\n", rv


