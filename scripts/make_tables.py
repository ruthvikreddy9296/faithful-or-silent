def tab_prompts():
    import prompts as P
    blocks = []
    for title, text in [("System prompt v2 (verdict-first; all configs except reason-first)",
                         P.GENERATOR_SYSTEM_V2),
                        ("System prompt v1-hardened (reason-first config only)",
                         P.GENERATOR_SYSTEM_V1_HARDENED),
                        ("User template", P.GENERATOR_USER_TEMPLATE)]:
        body = tex_escape(text.strip()).replace("\n", "\\par\n")
        blocks += [f"\\noindent\\textbf{{{tex_escape(title)}}}\\par\\smallskip",
                   "\\begin{quote}\\ttfamily\\footnotesize\\raggedright",
                   body,
                   "\\end{quote}\\bigskip", ""]
    return HEADER + "\n".join(blocks)


# ---------------------------------------------------------------- check mode
def check(numbers_txt):
    ok = True
    defined = set(re.findall(r"\\defrv\{([^}]+)\}", numbers_txt))
    sections = sorted((PAPER / "sections").glob("*.tex")) if (PAPER / "sections").exists() else []
    used = set()
    for f in sections:
        text = "\n".join(l for l in f.read_text().splitlines()
                         if not l.lstrip().startswith("%"))
        for key in re.findall(r"\\rv\{([^}]+)\}", text):
            used.add(key)
            if key not in defined:
                print(f"FAIL {f.name}: \\rv{{{key}}} not defined in numbers.tex")
                ok = False
        # bare result-like literals in prose (0.xxx proportions or xx.x% values)
        for pat in (r"(?<![\d.])0\.\d{2,}", r"\d+\.\d+\\%"):
            for m in re.findall(pat, text):
                print(f"FAIL {f.name}: bare numeric literal '{m}' — use an \\rv macro")
                ok = False
    unused = defined - used
    if sections and unused:
        print(f"note: {len(unused)} rv keys defined but not yet used (fine at skeleton stage)")
    return ok


