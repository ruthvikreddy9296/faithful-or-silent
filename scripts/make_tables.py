"""Generate paper/tables/*.tex and paper/numbers.tex from results/ files.

Every number that appears in the manuscript originates here, read directly from
the results files — nothing is hand-typed. Prose references values via
\\rv{key} macros defined in paper/numbers.tex (see paper/rvmacros.tex).

Usage:
  .venv/bin/python scripts/make_tables.py            # regenerate everything
  .venv/bin/python scripts/make_tables.py --check    # verify: no drift, all \\rv keys
                                                     # resolve, no bare literals in prose

Notes on the underlying files (verified 2026-09-01):
- phase1_frontier*.json rows are FA-sorted per arm -> ALWAYS join on the config
  name string in m["config"]; never rely on row order.
- recall_at_k is at each config's own k (3/5/8); never label a column "recall@5".
- phase1_retrieval_summary.json is stale (nulls for bge/pubmedbert); the per-run
  retrieval_report.json files are authoritative.
- accuracy_when_answering is conditional on answering (selection effect);
  coverage-normalized accuracy (correct/400) is recomputed here from completions.
- unparseable_rate's denominator is all 650 rows (both splits).
"""
