EMB_SHORT = {"all-MiniLM-L6-v2": "MiniLM", "bge-base-en-v1.5": "BGE",
             "pubmedbert-base-embeddings": "PubMedBERT"}


def tab_grid(runs):
    rows = []
    for c in CONFIG_ORDER:
        cfg, rep = runs[c]["cfg"], runs[c]["rep"]
        tail = cfg["embedding_model"].split("/")[-1]
        emb = EMB_SHORT.get(tail, tex_escape(tail))
        if cfg.get("no_context"):
            mode, emb = "none", "---"
        else:
            mode = cfg["retrieval"]
            if cfg.get("use_reranker"):
                mode += "{+}rr"
            if cfg.get("abstain_sim_threshold"):
                mode += "{+}gate"
        recall = num(rep["recall_at_k"]) if rep.get("recall_at_k") is not None else "---"
        if rep.get("holdout_leaks") not in (0, None):
            raise AssertionError(f"{c}: holdout_leaks = {rep['holdout_leaks']} (must be 0)")
        rows.append(f"{DISPLAY[c]} & {emb} & {mode} & "
                    f"{cfg['chunk_size_tokens']} & {cfg['top_k']} & {recall} \\\\")
    return HEADER + "\n".join([
        "\\begin{table}[!t]",
        "\\caption{Retrieval configuration grid. Recall@$k$ is measured at each",
        "configuration's own $k$ over the 400 answerable questions; the automated",
        "leak check finds zero held-out gold passages in any retrieved context, in",
        "every configuration. All configurations use the verdict-first prompt except",
        "reason-first; the closed-book control receives no context",
        "(parametric-leakage probe). rr = cross-encoder reranking.}",
        "\\label{tab:grid}",
        "\\centering\\footnotesize\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{lllrrr}",
        "\\toprule",
        "Config & Embed. & Retrieval & Chunk & $k$ & Recall@$k$ \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]) + "\n"


def tab_frontier(front, runs):
    rows = []
    for c in CONFIG_ORDER:
        rep = runs[c]["rep"]
        recall = num(rep["recall_at_k"]) if rep.get("recall_at_k") is not None else "---"
        cells = [DISPLAY[c], recall]
        for arm in ARMS:
            m = front[arm][c]
            lo, hi = m["false_answer_rate_ci95"]
            cells += [pct_bare(m["accuracy_when_answering"]),
                      pct_bare(m["false_refusal_rate"]),
                      f"{pct_bare(m['false_answer_rate'])} [{pct_bare(lo)}, {pct_bare(hi)}]"]
        rows.append(" & ".join(cells) + " \\\\")
    arm_heads = " & ".join(
        f"\\multicolumn{{3}}{{c}}{{{ARM_LABEL[a]}}}" for a in ARMS)
    sub = " & ".join(["Acc & FRR & FA [95\\% CI]"] * 3)
    return HEADER + "\n".join([
        "\\begin{table*}[!t]",
        "\\caption{The three-arm safe-failure frontier. All values are percentages;",
        "$n{=}400$ answerable and $n{=}250$ unanswerable questions per configuration.",
        "Acc = accuracy conditional on answering (selection effect: arms that refuse",
        "more answer a smaller, easier subset); FRR = false-refusal rate on answerable",
        "questions; FA = false-answer rate on unanswerable questions (lower is safer),",
        "with percentile-bootstrap 95\\% CIs (10{,}000 resamples, seed 42).}",
        "\\label{tab:frontier}",
        "\\centering\\footnotesize\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{lr" + "rrl" * 3 + "}",
        "\\toprule",
        f" & & {arm_heads} \\\\",
        "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}\\cmidrule(lr){9-11}",
        f"Config & Recall@$k$ & {sub} \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
    ]) + "\n"


